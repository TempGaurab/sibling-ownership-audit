#!/usr/bin/env python3
"""LaTeX macros and the Supplementary table for keyed-fingerprint power on declared copies (post hoc; DEVIATIONS.md, Nov 12,
entry 6c40f1e0353f). Formats values already in keyed_power.json (written by src/keyed_power.py); pooled rates are counts of
accepted copies over counts of copies across the cells named. Aggregate output only; every copy is our own model.
Usage: make_keyed_tables.py KEYED_POWER.json OUT_MACROS.tex OUT_TABLE.tex"""
import json, sys

FAM = {"qwen3": ("Qwenthree", "Qwen3-0.6B"), "tinyllama": ("Tinyllama", "TinyLlama-1.1B")}
CL = ("c0_ultrachat", "c1_oasst1", "c2_gsm8k")
ROWS = [  # (cell, label)
    ("ft_full_20", "Fine-tune, full weights, 20 steps"), ("ft_full_200", "Fine-tune, full weights, 200 steps"),
    ("ft_full_2000", "Fine-tune, full weights, 2{,}000 steps"), ("ft_lora16_20", "Fine-tune, LoRA, 20 steps"),
    ("ft_lora16_200", "Fine-tune, LoRA, 200 steps"), ("ft_lora16_2000", "Fine-tune, LoRA, 2{,}000 steps"),
    ("merge_90", "Merge, claimant weight 0.9"), ("merge_70", "Merge, claimant weight 0.7"),
    ("merge_50", "Merge, claimant weight 0.5"), ("merge_30", "Merge, claimant weight 0.3"),
    ("quant_8", "Quantize, 8 bits"), ("quant_4", "Quantize, 4 bits (NF4)"),
    ("prune_10", "Prune 10\\%"), ("prune_30", "Prune 30\\%"), ("prune_50", "Prune 50\\%"),
    ("student_1000", "Student, 1{,}000 responses"), ("student_10000", "Student, 10{,}000 responses"),
]
GROUPS = {  # macro stem -> cells pooled
    "LightFt": ["ft_full_20", "ft_lora16_20"],
    "LongFt": ["ft_full_200", "ft_full_2000", "ft_lora16_200", "ft_lora16_2000"],
    "MergeHigh": ["merge_90", "merge_70"], "MergeLow": ["merge_50", "merge_30"],
    "Quant": ["quant_8", "quant_4"], "PruneLight": ["prune_10"], "PruneHeavy": ["prune_50"],
    "Student": ["student_1000", "student_10000"],
}
def f2(x): return f"{x:.2f}"
def num(n): return f"{n:,}".replace(",", "{,}")


def pooled(g, cells):
    acc = sum(round(g[c]["power"] * g[c]["n"]) for c in cells); n = sum(g[c]["n"] for c in cells)
    return acc, n


def main():
    K = json.load(open(sys.argv[1])); M = {}
    for fam, (F, _) in FAM.items():
        D = K["families"][fam]; g = D["grid"]
        if D["n_copies"] != D["expected"] or set(g) != {c for c, _ in ROWS}:
            sys.exit(f"{fam}: incomplete grid")
        acc, n = pooled(g, list(g))
        M[f"kpCopies{F}"] = num(n); M[f"kpAccepted{F}"] = num(acc); M[f"kpPower{F}"] = f2(acc / n)
        M[f"kpCrossAccepts{F}"] = num(D["cross_accepts"]); M[f"kpCrossPairs{F}"] = num(D["cross_pairs"])
        M[f"kpPlainAccepts{F}"] = num(D["plain_copies"]["accepts"]); M[f"kpPlainPairs{F}"] = num(D["plain_copies"]["pairs"])
        M[f"kpPlainCopies{F}"] = num(D["plain_copies"]["n"])
        for stem, cells in GROUPS.items():
            a, m = pooled(g, cells); M[f"kp{stem}{F}"] = f2(a / m); M[f"kp{stem}N{F}"] = num(m)
        lf = [g[c]["power"] for c in GROUPS["LongFt"]]
        M[f"kpLongFtMin{F}"] = f2(min(lf)); M[f"kpLongFtMax{F}"] = f2(max(lf))
        M[f"kpPruneMid{F}"] = f2(g["prune_30"]["power"])
    M["kpCellN"] = str(K["families"]["qwen3"]["grid"]["ft_full_20"]["n"])
    M["kpSingleN"] = str(K["families"]["qwen3"]["grid"]["quant_8"]["n"])
    with open(sys.argv[2], "w") as f:
        f.write("% Generated by src/make_keyed_tables.py from data/analysis/keyed_power.json. Do not edit.\n")
        for k, v in M.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    T = ["% Generated by src/make_keyed_tables.py. Do not edit.",
         "\\begin{table}[h]\\centering\\small",
         "\\caption{\\textbf{Power of the keyed fingerprint on declared copies (post hoc).} Fraction of each keyed claimant's copies "
         "accepted under its own key, with the rule unchanged (at least one of 20 greedy responses begins with its secret response), "
         "pooled over the three claimants; in brackets the mean fraction of the 20 keys reproduced. Per claimant: power for "
         "UltraChat, OASST1 and GSM8K claimants. Stochastic cells have 15 copies (5 per claimant); quantization and pruning are "
         "deterministic and have 3. No copy was accepted under another claimant's key, and no copy of a claimant without a key "
         "was accepted (counts in Supplementary Note~10).}\\label{tab:si-keyed}",
         "\\adjustbox{max width=\\textwidth}{\\begin{tabular}{lcccc}", "\\hline",
         " & \\multicolumn{2}{c}{Qwen3-0.6B} & \\multicolumn{2}{c}{TinyLlama-1.1B} \\\\",
         "Copy & Power (keys hit) & Per claimant & Power (keys hit) & Per claimant \\\\", "\\hline"]
    for c, label in ROWS:
        cells = []
        for fam in FAM:
            r = K["families"][fam]["grid"][c]
            pc = "/".join("--" if r["per_claimant"][k] is None else f2(r["per_claimant"][k]) for k in CL)
            cells += [f"{f2(r['power'])} ({f2(r['mean_hit_fraction'])})", pc]
        T.append(f"{label} & " + " & ".join(cells) + " \\\\")
    tot = []
    for fam, (F, _) in FAM.items():
        tot += [f"{M['kpPower' + F]} ({M['kpAccepted' + F]}/{M['kpCopies' + F]})", ""]
    T += ["\\hline", "All copies & " + " & ".join(tot) + " \\\\", "\\hline", "\\end{tabular}}", "\\end{table}"]
    open(sys.argv[3], "w").write("\n".join(T) + "\n")
    print(f"KEYED_TABLES_OK macros={len(M)}")


if __name__ == "__main__":
    main()
