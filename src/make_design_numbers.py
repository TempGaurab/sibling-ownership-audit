#!/usr/bin/env python3
"""Design counts for Methods as LaTeX macros, from committed provenance files only: census, download list, weight check, stratum
agreement. No score enters. Writes design_numbers.tex. Usage: make_design_numbers.py"""
import ast, collections, json, re, sys
L = json.load(open("data/hub/download_list.json"))["rows"]; T = json.load(open("data/hub/topup_list.json"))
sib = [r for r in L if r["role"] == "sibling"]; ctl = [r for r in L if r["role"] == "control"]
last = {}
for l in open("data/hub/weight_check_v2.jsonl"):
    r = json.loads(l); last[r["id"]] = r
fam = {r["id"]: r["family"] for r in sib}; ok = collections.Counter(fam[i] for i, r in last.items() if r["passed"] and i in fam)
A = open("data/strata/agreement.txt").read(); m = re.search(r"data_overlap pooled: kappa ([\d.]+), raw agreement ([\d.]+)", A); nsample = re.search(r"final, models=(\d+)", A).group(1)
n = lambda x: f"{x:,}".replace(",", "{,}")
M = dict(HubSampled=n(int(nsample)), HubLicensed=n(len(sib)), HubPassed=n(sum(ok.values())), HubPassedQwen=n(ok["qwen3"]), HubPassedTiny=n(ok["tinyllama"]),
         ControlsSampled=n(len(ctl)), ControlBases=str(len({r["base"] for r in ctl})), ControlReserves=n(len(T["rows"])), ReservePerBase=str(T["reserve_per_base"]), KappaOverlap=m.group(1), RawOverlap=m.group(2))
# Usable independent controls after the Nov 9 replacement rule, per family, from merge_topup.py's lines synced in data/hub/topup_merge.txt.
TL = [l.strip() for l in open("data/hub/topup_merge.txt") if not l.startswith("#")]
if not any(l.endswith("WATCH_DONE merge_failed=0") for l in TL): sys.exit("top-up merge did not finish cleanly")
for fam, key in (("qwen3", "Qwen"), ("tinyllama", "Tiny")):
    i = next(j for j, l in enumerate(TL) if l.startswith(fam + " appended"))
    m = re.search(r"usable (\d+) bases (\d+) floor met (\w+)", TL[i]); per = ast.literal_eval(TL[i + 1])
    if m.group(3) != "True" or int(m.group(1)) != sum(c for _, c in per) or int(m.group(2)) != len(per): sys.exit(f"inconsistent top-up lines for {fam}")
    M[f"ControlsUsable{key}"], M[f"ControlBasesUsable{key}"] = n(int(m.group(1))), m.group(2)
    M[f"ControlsPerBaseMin{key}"], M[f"ControlsPerBaseMax{key}"] = str(min(c for _, c in per)), str(max(c for _, c in per))
M["ControlsPerBaseMin"] = str(min(int(M["ControlsPerBaseMinQwen"]), int(M["ControlsPerBaseMinTiny"])))
open("design_numbers.tex", "w").write("% Generated by src/make_design_numbers.py from provenance files. Do not edit.\n" + "".join(f"\\newcommand{{\\design{k}}}{{{v}}}\n" for k, v in M.items())); print(M)
