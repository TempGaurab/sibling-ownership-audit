#!/usr/bin/env python3
"""LaTeX macros and a Supplementary table from data/strata/human_agreement.json (Nov 12 deviation 6c40f1e0353f, post hoc).
Reporting only: rounding and counts of values already in the JSON. Usage: make_human_tables.py AGREEMENT.json OUT_MACROS.tex OUT_TABLE.tex"""
import json, sys

R, mo, to = json.load(open(sys.argv[1])), sys.argv[2], sys.argv[3]
f2 = lambda x: f"{x:.2f}"; F = R["fields"]
M = dict(hcCards=str(R["n_cards"]), hcPopulation=f"{sum(g['population'] for g in R['groups'].values()):,}".replace(",", "{,}"),
         hcNamed=str(R["groups"]["named"]["sampled"]), hcDisagree=str(R["groups"]["disagree"]["sampled"]),
         hcRandom=str(R["groups"]["stated"]["sampled"] + R["groups"]["unknown"]["sampled"]))
for key, nm in (("stratum label (same/partial vs other)", "Label"), ("overlap pooled", "Overlap"), ("dataset stated at all", "Stated"),
                ("recipe_family", "Recipe"), ("teacher_use", "Teacher")):
    m = F[key]["merged"]
    M[f"hcKappa{nm}"], M[f"hcAgree{nm}"] = f2(m["sample"]["kappa"]), f2(m["sample"]["agreement"])
    M[f"hcWKappa{nm}"], M[f"hcWAgree{nm}"] = f2(m["weighted"]["kappa"]), f2(m["weighted"]["agreement"])
X = R["dataset_stated_crosstab"]
M["hcHumanUnknownLlmStated"], M["hcHumanStatedLlmUnknown"] = str(X["human_unknown|llm_stated"]), str(X["human_stated|llm_unknown"])
M["hcRecipeUnknownFull"] = str(R["recipe_crosstab_offdiag"].get("human_unknown|llm_full", 0))
SP = R["same_or_partial"]
M["hcSpHuman"], M["hcSpLlm"] = str(sum(v["human"] for v in SP.values())), str(sum(v["llm"] for v in SP.values()))
M["hcSpHumanOnly"], M["hcSpLlmOnly"] = str(sum(v["human_only"] for v in SP.values())), str(sum(v["llm_only"] for v in SP.values()))
with open(mo, "w") as fh:
    fh.write("% Generated by src/make_human_tables.py from data/strata/human_agreement.json. Do not edit.\n")
    fh.write("".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(M.items())))
rows = []
for key, label in (("overlap[ultrachat]", "Data overlap, UltraChat"), ("overlap[oasst1]", "Data overlap, OASST1"), ("overlap[gsm8k]", "Data overlap, GSM8K"),
                   ("overlap pooled", "Data overlap, pooled"), ("dataset stated at all", "Any dataset stated"),
                   ("stratum label (same/partial vs other)", "Same or partial vs other"), ("recipe_family", "Recipe family"), ("teacher_use", "Teacher use")):
    v = F[key]
    cells = [f"{f2(v[r]['sample']['kappa'])} ({f2(v[r]['sample']['agreement'])})" for r in ("merged", "pass1", "pass2")]
    cells.append(f"{f2(v['merged']['weighted']['kappa'])} ({f2(v['merged']['weighted']['agreement'])})")
    rows.append(f"{label} & " + " & ".join(cells) + r" \\")
with open(to, "w") as fh:
    fh.write("% Generated by src/make_human_tables.py. Do not edit.\n")
    fh.write(r"""\begin{table}[h]\centering\small
\caption{\textbf{Agreement between one human coder and the LLM stratum codes (post hoc).} Cohen's $\kappa$ with raw agreement in brackets, on """
             + M["hcCards"] + r""" sampled model cards. Merged: the code used in the analysis, with disagreements between the two LLM passes set to unknown. Weighted: agreement with the merged code, reweighted to all """
             + M["hcPopulation"] + r""" distinct cards by inverse sampling fraction. The sample over-represents cards that name a claimant dataset and cards on which the passes disagreed. The human coder is an author.}\label{tab:si-human}
\adjustbox{max width=\textwidth}{\begin{tabular}{lcccc}
\hline
Field & Merged & Pass 1 & Pass 2 & Merged, weighted \\
\hline
""" + "\n".join(rows) + "\n" + r"""\hline
\end{tabular}}
\end{table}
""")
print("HUMAN_TABLES_DONE", len(M))
