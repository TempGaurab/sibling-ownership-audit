#!/usr/bin/env python3
"""Macros and a Supplementary table from the post hoc fidelity check (data/analysis/fidelity.json, src/fidelity_check.py).
Reporting only: formats values already computed. Values reported by the source papers are not read here; the text cites them.
Usage: make_fidelity_numbers.py FIDELITY.json OUTDIR"""
import json, os, sys

FAM = {"qwen3": ("Qwen3-0.6B", "Qwenthree"), "tinyllama": ("TinyLlama-1.1B", "Tinyllama")}
POP = [("control", "Independent controls"), ("sib|high", "Controlled siblings, high"), ("sib|mid", "Controlled siblings, mid"), ("sib|low", "Controlled siblings, low"), ("hub", "Hub siblings"),
       ("copy|ft_full", "Copies, full fine-tuning"), ("copy|ft_lora16", "Copies, LoRA fine-tuning"), ("copy|merge", "Copies, merging"), ("copy|quant", "Copies, quantization"),
       ("copy|prune", "Copies, pruning"), ("copy|student", "Copies, student")]
CLAIM = (("c0_ultrachat", "UltraChat"), ("c1_oasst1", "OASST1"), ("c2_gsm8k", "GSM8K"))


def f2(x): return "--" if x is None else f"{x:.2f}"
def f3(x): return "--" if x is None else f"{x:.3f}"
def num(n): return f"{n:,}".replace(",", "{,}")


def main():
    R, out = json.load(open(sys.argv[1])), sys.argv[2]; os.makedirs(out, exist_ok=True); M = {}
    for f, (_, F) in FAM.items():
        own = [v["claimant_prefers_target"] for v in R[f"{f}|llmprint_search"]["own_bits"].values()]
        M[f"fidOwnMin{F}"], M[f"fidOwnMax{F}"] = f"{100 * min(own):.0f}", f"{100 * max(own):.0f}"
        loss = [v["median"] for v in R[f"{f}|llmprint_search"]["final_loss"].values()]
        M[f"fidLossMin{F}"], M[f"fidLossMax{F}"] = f3(min(loss)), f3(max(loss))
        pos = R[f"{f}|llmprint_positive_rate"]
        M[f"fidCtrlPos{F}"] = f2(pos["control"]["rate"])
        cp = [v["rate"] for k, v in pos.items() if k.startswith("copy|")]
        M[f"fidCopyPosMin{F}"], M[f"fidCopyPosMax{F}"] = f2(min(cp)), f2(max(cp))
        M[f"fidFtPos{F}"] = f2(max(pos["copy|ft_full"]["rate"], pos["copy|ft_lora16"]["rate"]))
        re = R[f"{f}|reef_cka"]
        M[f"fidReefCtrl{F}"] = f2(re["control"]["median"]); M[f"fidReefCtrlLo{F}"] = f2(re["control"]["q05"])
        cm = [v["median"] for k, v in re.items() if k.startswith("copy|")]
        M[f"fidReefCopyMin{F}"], M[f"fidReefCopyMax{F}"] = f2(min(cm)), f2(max(cm))
        sm = [re[k]["median"] for k in ("sib|high", "sib|mid", "sib|low")]
        M[f"fidReefSibMin{F}"], M[f"fidReefSibMax{F}"] = f2(min(sm)), f2(max(sm))
    allown = [v["claimant_prefers_target"] for f in FAM for v in R[f"{f}|llmprint_search"]["own_bits"].values()]
    M["fidOwnMin"], M["fidOwnMax"] = f"{100 * min(allown):.0f}", f"{100 * max(allown):.0f}"
    allctrl = [R[f"{f}|llmprint_positive_rate"]["control"]["rate"] for f in FAM]
    M["fidCtrlPosMin"], M["fidCtrlPosMax"] = f2(min(allctrl)), f2(max(allctrl))
    open(f"{out}/fidelity_numbers.tex", "w").write("% Generated by src/make_fidelity_numbers.py from data/analysis/fidelity.json. Do not edit.\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(M.items())))
    # Supplementary table.
    rows = []
    for f, (name, _) in FAM.items():
        rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{name}}}}}\\\\")
        re, ag, pos = R[f"{f}|reef_cka"], R[f"{f}|llmprint_agreement"], R[f"{f}|llmprint_positive_rate"]
        for k, nm in POP:
            a, b, c = re.get(k), ag.get(k), pos.get(k)
            rows.append(" & ".join([nm, num(a["n"]) if a else "--", f"{f3(a['median'])} ({f3(a['q05'])}--{f3(a['q95'])})" if a else "--",
                                    f"{f3(b['median'])} ({f3(b['q05'])}--{f3(b['q95'])})" if b else "--", num(c["n"]) if c else "--", f2(c["rate"]) if c else "--"]) + "\\\\")
        s = R[f"{f}|llmprint_search"]
        rows.append("\\quad LLMPrint search, by claimant & \\multicolumn{5}{p{0.66\\linewidth}}{" + "; ".join(
            f"{lab}: target preferred on {100 * s['own_bits'][c]['claimant_prefers_target']:.0f}\\% of {s['own_bits'][c]['usable']} prompts, median final loss {f3(s['final_loss'][c]['median'])}" for c, lab in CLAIM) + "}\\\\")
    cap = ("\\textbf{Fidelity check of the REEF and LLMPrint reimplementations.} Post hoc, computed after the confirmatory analysis from existing outputs, "
           "with no model run and no rule changed (deviations log, 12 November). REEF: linear CKA with the claimant at the layer matching layer 18 of 31, median "
           "with 5th and 95th percentiles over claimant-suspect pairs. LLMPrint: bit agreement with the claimant's own bits on its 300 fingerprint prompts, and the "
           "rate at which the frozen rule declares a suspect derived; the 13 validation controls are excluded. Copies are true derivatives and independent "
           "controls are unrelated models, the populations on which the source papers report their results. The loss minimum of the LLMPrint objective at the "
           "paper's setting $\\alpha=0.5$ is $\\log 2\\approx0.693$, reached at a zero margin.")
    t = ["\\begin{footnotesize}", "\\setlength{\\tabcolsep}{3.5pt}", "\\begin{longtable}{@{}l r c c r r@{}}", f"\\caption{{{cap}}}\\label{{tab:si-fidelity}}\\\\", "\\toprule",
         "Population & $n$ & REEF CKA & LLMPrint agreement & $n$ & Declared derived\\\\", "\\midrule", "\\endfirsthead", "\\toprule",
         "Population & $n$ & REEF CKA & LLMPrint agreement & $n$ & Declared derived\\\\", "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"] + rows + ["\\end{longtable}", "\\end{footnotesize}"]
    open(f"{out}/si_table_fidelity.tex", "w").write("% Generated by src/make_fidelity_numbers.py from data/analysis/fidelity.json. Do not edit.\n" + "\n".join(t) + "\n")
    print("FIDELITY_NUMBERS_DONE", len(M))


if __name__ == "__main__":
    main()
